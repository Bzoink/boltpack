#!/usr/bin/env python3
"""Run the crypto layer (src/core/crypto) on emulated Atari hardware in Hatari.

Builds test/atari/crypto_check.c (with the library, suites S1 and S2) for the 68000 and, with
--emutos, for the 68030 of an emulated TT, generates crypto_vectors.h from the repository's
reference files, and runs the result.  The program first checks known answers and golden frames
(Ascon-AEAD128 and XOF128 known-answer records, the XChaCha20-Poly1305 draft vector, BLAKE2b,
key derivation including Argon2id, sealed frames, commitments): the first big-endian run of the
crypto layer.  It then times, in 200 Hz ticks of emulated time: raw AEAD sealing of 32 KiB, bp_frame_seal
(hedged nonce included) on 32 KiB kind 2 frames for both suites, and one Argon2id run.

These are emulator figures: they say nothing about real hardware beyond the instruction mix.

usage: python3 test/check_hatari_crypto.py --tos TOS162 [--emutos ETOS512] [--argon-kib N]
"""
import argparse, json, os, re, shutil, subprocess, sys, tempfile, time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "test" / "reference" / "encryption"
C = ROOT / "src" / "core" / "crypto"


def records(path):
    rec = {}
    for line in open(path):
        line = line.strip()
        if not line:
            if rec: yield rec; rec = {}
            continue
        k, _, v = line.partition("=")
        rec[k.strip()] = v.strip()
    if rec: yield rec


def s(x):
    return '"%s"' % x


s_ = s


def make_vectors(path):
    aead = [r for i, r in enumerate(records(REF / "LWC_AEAD_KAT_128_128.txt")) if i % 41 == 0]
    xof = [r for i, r in enumerate(records(REF / "LWC_XOF_KAT_128_512_first129.txt")) if i % 5 == 0]
    txt = (REF / "xchacha-draft-03-A1.txt").read_text()
    def sect(label, end):
        t = txt[txt.index(label) + len(label):]
        t = t[:t.index(end)]
        out = bytearray()
        for ln in t.splitlines():
            m = re.match(r"\s+[0-9a-f]{3}\s+((?:[0-9a-f]{2} )+)", ln)
            if m: out += bytes.fromhex(m.group(1).replace(" ", ""))
        return bytes(out)
    pt, ad = sect("Plaintext:", "AAD:"), sect("AAD:", "Key:")
    key, iv, ct = sect("Key:", "IV:"), sect("IV:", "32-bit fixed-common part:"), sect("Ciphertext:", "Tag:")
    tag = bytes.fromhex(re.search(r"Tag:\s+([0-9a-f:]+)", txt).group(1).replace(":", ""))
    b2 = re.sub(r"[^0-9A-Fa-f]", "", (REF / "rfc7693-blake2b-abc.txt").read_text().split("\n\n", 1)[1].split("=", 1)[1]).lower()
    gold = json.load(open(REF / "golden-crypto-v1.json"))["cases"]
    L = ["/* generated by check_hatari_crypto.py from test/reference/encryption */",
         "typedef struct { const char *key, *nonce, *pt, *ad, *ct; } aead_kat;",
         "typedef struct { const char *msg, *md; } xof_kat;",
         "typedef struct { int kdf, aead, norm; unsigned long m; int t, lanes; const char *salt, *set8, *secret, *k_seal, *k_nonce, *verifier; } derive_case;",
         "typedef struct { int aead; const char *set8, *k_seal, *k_nonce; unsigned long ctr; const char *E, *envelope, *extra, *pt, *nonce, *ct, *tag; } frame_case;",
         "typedef struct { int aead; const char *tags[5]; const char *commit, *table_hash; } commit_case;"]
    L.append("static const aead_kat AEAD_KATS[] = {")
    for r in aead: L.append("  { %s, %s, %s, %s, %s }," % tuple(s(r[k]) for k in ("Key", "Nonce", "PT", "AD", "CT")))
    L.append("};\n#define N_AEAD %d" % len(aead))
    L.append("static const xof_kat XOF_KATS[] = {")
    for r in xof: L.append("  { %s, %s }," % (s(r["Msg"]), s(r["MD"].lower())))
    L.append("};\n#define N_XOF %d" % len(xof))
    L.append("static const char *XCHACHA[] = { %s };" % ", ".join(s(x.hex()) for x in (key, iv, ad, pt, ct + tag)))
    L.append("static const char *BLAKE2B_ABC = %s;" % s(b2))
    d = [c for c in gold if c["kind"] == "derive"]
    L.append("static const derive_case DERIVE[] = {")
    for c in d:
        L.append("  { %d, %d, %d, %dUL, %d, %d, %s, %s, %s, %s, %s, %s }," % (c["kdf"], c["aead"], c["norm"], c["m"], c["t"], c["lanes"], s(c["salt"]), s(c["set8"]), s(c["secret"]), s(c["k_seal"]), s(c["k_nonce"]), s(c["verifier"])))
    L.append("};\n#define N_DERIVE %d" % len(d))
    fr = [c for c in gold if c["kind"] == "frame"]
    L.append("static const frame_case FRAMES[] = {")
    for c in fr:
        L.append("  { %d, %s, %s, %s, %dUL, %s, %s, %s, %s, %s, %s, %s }," % (c["aead"], s(c["set8"]), s(c["k_seal"]), s(c["k_nonce"]), c["ctr"], s(c["E"]), s(c["envelope"]), s(c["extra"]), s(c["pt"]), s(c["nonce"]), s(c["ct"]), s(c["tag"])))
    L.append("};\n#define N_FRAME %d" % len(fr))
    cm = [c for c in gold if c["kind"] == "commit"]
    L.append("static const commit_case COMMITS[] = {")
    for c in cm: L.append("  { %d, { %s }, %s, %s }," % (c["aead"], ", ".join(s(t) for t in c["tags"]), s(c["commit"]), s(c["table_hash"])))
    L.append("};\n#define N_COMMIT %d" % len(cm))
    # entropy pool expectations from the independent Python model (no OS source, imported bytes, draws)
    sys.path.insert(0, str(ROOT / "test"))
    import bp8_crypto as M
    pools = [(bytes(range(0x40, 0x50)), [32, 32]), (bytes(range(1, 33)), [1, 7, 8, 9, 64]), (bytes(range(0x80, 0x91)), [100, 3])]
    L.append("typedef struct { const char *imp; int ndraw; unsigned draws[6]; const char *out; } pool_case;")
    L.append("static const pool_case POOLS[] = {")
    for imp, dr in pools:
        L.append("  { %s, %d, { %s }, %s }," % (s_(imp.hex()), len(dr), ", ".join(str(x) for x in dr), s_(M.pool_model(imp, dr).hex())))
    L.append("};\n#define N_POOL %d" % len(pools))
    path.write_text("\n".join(L) + "\n")


def build(cc, flags, out, work):
    srcs = [ROOT / "test/atari/crypto_check.c"] + [C / f for f in ("bp_cutil.c", "bp_crypto.c", "bp_entropy.c", "bp_entropy_os_none.c", "bp_ascon_c89.c", "bp_s1.c")] + [C / "vendor/monocypher/monocypher.c"]
    cmd = [cc, "-std=gnu99", "-O2", "-Wall", "-Wno-unused-function", "-DBP_CRYPTO_S1", "-DBP_CRYPTO_TESTING", "-I" + str(C), "-I" + str(work)] + flags + [str(x) for x in srcs] + ["-o", str(out)]
    subprocess.run(cmd, check=True, timeout=600)


def run(hatari, machine, tos, drive, timeout):
    env = os.environ.copy()
    env.update(SDL_VIDEODRIVER="dummy", SDL_AUDIODRIVER="dummy")
    result = drive / "CRYPTO.TXT"
    argv = [hatari, "--machine", machine, "--tos", str(tos), "--sound", "off", "--confirm-quit", "off",
            "--fast-forward", "on", "--fast-boot", "on", "--memsize", "14", "--harddrive", str(drive),
            "--auto", r"C:\CHECK.TOS", "--run-vbls", "20000000"]
    proc = subprocess.Popen(argv, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, env=env)
    try:
        deadline = time.time() + timeout
        while time.time() < deadline:
            if result.exists() and "done failures" in result.read_text(errors="replace"): break
            if proc.poll() is not None: break
            time.sleep(1)
    finally:
        proc.kill(); proc.wait()
    return (result.read_text(errors="replace") if result.exists() else ""), argv


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tos", type=Path, required=True)
    ap.add_argument("--emutos", type=Path)
    ap.add_argument("--hatari", default="hatari")
    ap.add_argument("--cc", default="m68k-atari-mint-gcc")
    ap.add_argument("--timeout", type=int, default=3600)
    ap.add_argument("--argon-kib-68000", type=int, default=1024)
    ap.add_argument("--argon-kib-68030", type=int, default=8192)
    ap.add_argument("--min-ticks", type=int, default=1000)
    ap.add_argument("--only", choices=("68000", "68030"))
    args = ap.parse_args()
    if shutil.which(args.cc) is None or shutil.which(args.hatari) is None:
        print("SKIPPED: needs %s and %s" % (args.cc, args.hatari)); return 0
    work = Path(tempfile.mkdtemp(prefix="bp-hatari-crypto-"))
    make_vectors(work / "crypto_vectors.h")
    bad = 0
    plan = [("68000 (ST/STE, 8 MHz)", "68000", "ste", args.tos, ["-m68000"], args.argon_kib_68000)]
    if args.emutos: plan.append(("68030 (TT, 32 MHz)", "68030", "tt", args.emutos, ["-m68030"], args.argon_kib_68030))
    for label, key, machine, tos, flags, kib in plan:
        if args.only and args.only != key: continue
        drive = work / key; drive.mkdir()
        build(args.cc, flags + ["-DARGON_KIB=%dUL" % kib, "-DMIN_TICKS=%dL" % args.min_ticks], drive / "CHECK.TOS", work)
        text, argv = run(args.hatari, machine, tos, drive, args.timeout)
        ver = subprocess.run([args.hatari, "--version"], capture_output=True, text=True).stdout.strip().splitlines()
        print("== %s: %s -O2 %s -DARGON_KIB=%d" % (label, args.cc, " ".join(flags), kib))
        print("   %s; CPU and timing settings are Hatari's defaults for the machine (no --cpu-exact or --cpuclock given); command: %s" % (ver[0] if ver else "hatari (version unknown)", " ".join(argv[:12])))
        print(text.rstrip())
        if "done failures 0" not in text or "FAIL" in text: bad += 1
    shutil.rmtree(work)
    print("check_hatari_crypto: %s" % ("FAILED" if bad else "passed"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
