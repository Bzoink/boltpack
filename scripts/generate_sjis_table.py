#!/usr/bin/env python3
"""Generate the strict JIS X 0208 tables used by BP_CP_SJIS."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/core/bp_sjis_table.h"
LEADS = tuple(range(0x81, 0xA0)) + tuple(range(0xE0, 0xF0))
TRAILS = tuple(range(0x40, 0x7F)) + tuple(range(0x80, 0xFD))


def main():
    dense = []
    reverse = {}
    for lead in LEADS:
        for trail in TRAILS:
            try:
                decoded = bytes((lead, trail)).decode("shift_jis")
                codepoint = ord(decoded) if len(decoded) == 1 else 0
            except UnicodeDecodeError:
                codepoint = 0
            dense.append(codepoint)
            if codepoint:
                reverse.setdefault(codepoint, (lead << 8) | trail)

    reverse = sorted(reverse.items())
    with OUTPUT.open("w", encoding="ascii", newline="\n") as output:
        output.write("/* Standard Shift-JIS/JIS X 0208 mappings; generated by\n")
        output.write(" * scripts/generate_sjis_table.py using Python's strict codec. */\n")
        output.write("#ifndef BP_SJIS_TABLE_H\n#define BP_SJIS_TABLE_H\n\n")
        output.write("typedef struct { unsigned short unicode; unsigned short sjis; } bp_sjis_reverse_t;\n")
        output.write(f"static const unsigned short bp_sjis_to_unicode[{len(dense)}] = {{\n")
        for offset in range(0, len(dense), 12):
            row = ", ".join(f"0x{value:04X}" for value in dense[offset:offset + 12])
            output.write(f"    {row},\n")
        output.write("};\n\n")
        output.write(f"static const bp_sjis_reverse_t bp_unicode_to_sjis[{len(reverse)}] = {{\n")
        for offset in range(0, len(reverse), 6):
            row = ", ".join(
                f"{{0x{codepoint:04X}, 0x{sjis:04X}}}"
                for codepoint, sjis in reverse[offset:offset + 6]
            )
            output.write(f"    {row},\n")
        output.write("};\n\n")
        output.write(f"#define BP_SJIS_REVERSE_COUNT {len(reverse)}U\n\n#endif\n")
    print(f"wrote {OUTPUT} ({len(reverse)} Unicode mappings)")


if __name__ == "__main__":
    main()
