#!/usr/bin/env python3
"""Generate src/core/boltlz_m68k_c68.s from src/core/boltlz_m68k.S.

The Sinclair QL's c68 toolchain assembles with as68, which uses a different
dialect from GNU as and has no macros. The 68000 code in boltlz_m68k.S is
position-independent (PC-relative branches only, no relocations), so the
GNU-assembled machine code is emitted unchanged as as68 data words with the
two entry labels at their offsets. The 68000 variant is used: the QL's
68008 and later QL-compatibles all run it.

    python3 scripts/gen_boltlz_m68k_c68.py            # rewrite the file
    python3 scripts/gen_boltlz_m68k_c68.py --check    # fail if out of date
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/core/boltlz_m68k.S"
OUTPUT = ROOT / "src/core/boltlz_m68k_c68.s"
ENTRIES = ("_bl68_encode", "_bl68_decode")


def tool(prefix, name):
    return prefix + name


def generate(prefix):
    with tempfile.TemporaryDirectory() as tmp:
        obj = Path(tmp) / "boltlz_m68k.o"
        raw = Path(tmp) / "text.bin"
        subprocess.run([tool(prefix, "gcc"), "-m68000", "-c", str(SOURCE), "-o", str(obj)],
                       check=True)
        relocs = subprocess.run([tool(prefix, "objdump"), "-r", str(obj)], check=True,
                                capture_output=True, text=True).stdout
        if any(line[:1].isdigit() for line in relocs.splitlines()):
            raise SystemExit("boltlz_m68k.S has relocations; it can no longer be "
                             "emitted as position-independent data:\n" + relocs)
        headers = subprocess.run([tool(prefix, "objdump"), "-h", str(obj)], check=True,
                                 capture_output=True, text=True).stdout
        for line in headers.splitlines():
            fields = line.split()
            if len(fields) > 2 and fields[1] in (".data", ".bss") and int(fields[2], 16):
                raise SystemExit("boltlz_m68k.S has a %s section" % fields[1])
        subprocess.run([tool(prefix, "objcopy"), "-O", "binary", "-j", ".text",
                        str(obj), str(raw)], check=True)
        code = raw.read_bytes()
        symbols = {}
        for line in subprocess.run([tool(prefix, "nm"), str(obj)], check=True,
                                   capture_output=True, text=True).stdout.splitlines():
            fields = line.split()
            if len(fields) == 3 and fields[1] == "T":
                symbols[fields[2]] = int(fields[0], 16)
    if sorted(symbols) != sorted(ENTRIES) or len(code) % 2:
        raise SystemExit("unexpected symbols or size: %r, %d bytes" % (symbols, len(code)))
    labels = {offset: name for name, offset in symbols.items()}
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    out = [
        "! boltlz_m68k_c68.s -- boltlz_m68k.S for the c68/as68 toolchain (Sinclair QL)",
        "! Generated by scripts/gen_boltlz_m68k_c68.py; do not edit.",
        "! Source sha256 %s" % digest,
        "! The 68000 machine code of boltlz_m68k.S, which is position-independent,",
        "! as data words; see that file for the code and its interface.",
        "\t.sect\t.text",
        "\t.align\t2",
    ]
    for name in ENTRIES:
        out.append("\t.extern\t%s" % name)
    words = [int.from_bytes(code[i:i + 2], "big") for i in range(0, len(code), 2)]
    line = []
    for index, word in enumerate(words):
        offset = index * 2
        if offset in labels:
            if line:
                out.append("\t.data2\t" + ",".join(line))
                line = []
            out.append(labels[offset] + ":")
        line.append(str(word - 0x10000 if word >= 0x8000 else word))
        if len(line) == 8:
            out.append("\t.data2\t" + ",".join(line))
            line = []
    if line:
        out.append("\t.data2\t" + ",".join(line))
    return "\n".join(out) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="fail if the file is out of date")
    p.add_argument("--cross-prefix", default=os.environ.get("M68K_CROSS_PREFIX", "m68k-atari-mint-"),
                   help="GNU m68k toolchain prefix (default m68k-atari-mint-)")
    args = p.parse_args()
    if not shutil.which(args.cross_prefix + "gcc"):
        print("SKIP  %sgcc not found; cannot regenerate %s" %
              (args.cross_prefix, OUTPUT.relative_to(ROOT)))
        return 0 if args.check else 1
    text = generate(args.cross_prefix)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print("%s is out of date; run scripts/gen_boltlz_m68k_c68.py" %
                  OUTPUT.relative_to(ROOT))
            return 1
        print("%s matches boltlz_m68k.S" % OUTPUT.relative_to(ROOT))
        return 0
    OUTPUT.write_text(text)
    print("wrote", OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
